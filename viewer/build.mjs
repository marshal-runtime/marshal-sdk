// Builds @omer/marshal-sdk-sessions into out/package (manifest, dist/runtime.cjs, README) and its tests.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = path.dirname(fileURLToPath(import.meta.url));
const generated = path.join(root, "src", "generated");
mkdirSync(generated, { recursive: true });
writeFileSync(
  path.join(generated, "view.ts"),
  `// Generated by build.mjs from src/view.html.\nexport const VIEW_HTML: string = ${JSON.stringify(readFileSync(path.join(root, "src", "view.html"), "utf8"))};\n`,
);

// The host loader serves some built-ins only bare, others only under node:.
const loaderBuiltins = {
  name: "loader-builtins",
  setup(context) {
    context.onResolve({ filter: /^node:(fs|path|os|zlib|http|https)$/ }, (args) => ({ path: args.path.slice(5), external: true }));
    context.onResolve({ filter: /^(crypto)$/ }, (args) => ({ path: `node:${args.path}`, external: true }));
  },
};

const out = path.join(root, "out", "package");
rmSync(out, { recursive: true, force: true });
await build({
  entryPoints: [path.join(root, "src", "index.ts")],
  outfile: path.join(out, "dist", "runtime.cjs"),
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node20",
  plugins: [loaderBuiltins],
  logLevel: "warning",
});
const manifest = JSON.parse(readFileSync(path.join(root, "runtime-extension.json"), "utf8"));
manifest.contributes.capabilities = createRequire(import.meta.url)(path.join(out, "dist", "runtime.cjs")).CAPABILITY_NAMES;
writeFileSync(path.join(out, "runtime-extension.json"), `${JSON.stringify(manifest, null, 2)}\n`);
cpSync(path.join(root, "README.md"), path.join(out, "README.md"));
writeFileSync(path.join(out, "package.json"), `${JSON.stringify({ name: manifest.identity, version: manifest.version, private: true, type: "commonjs", main: manifest.entrypoint }, null, 2)}\n`);

await build({
  entryPoints: ["store", "pages", "questions", "cloud", "shared", "review", "artifacts", "cache", "cloud-pages"].map((name) => path.join(root, "test", `${name}.test.ts`)),
  outdir: path.join(root, "out", "test"),
  outExtension: { ".js": ".cjs" },
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node22",
  logLevel: "warning",
});
